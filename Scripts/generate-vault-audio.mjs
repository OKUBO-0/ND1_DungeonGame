import fs from 'node:fs';
import path from 'node:path';
const folder=path.resolve('SourceAssets/Audio/Vault');fs.mkdirSync(folder,{recursive:true});
const rate=22050,tau=Math.PI*2;let seed=7823;
const noise=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/2147483648-1;};
const hz=midi=>440*2**((midi-69)/12);
const bell=(t,f)=>t<0||t>2.5?0:(1-Math.exp(-t*180))*Math.exp(-t*3)*(Math.sin(tau*f*t)+0.32*Math.sin(tau*f*2.007*t)+0.1*Math.sin(tau*f*3.92*t));
function write(name,duration,render,peak=0.72){
  const count=Math.round(duration*rate),samples=new Float32Array(count);let max=0;
  for(let i=0;i<count;i++){samples[i]=render(i/rate,i);max=Math.max(max,Math.abs(samples[i]));}
  const buffer=Buffer.alloc(44+count*2);buffer.write('RIFF');buffer.writeUInt32LE(buffer.length-8,4);buffer.write('WAVEfmt ',8);buffer.writeUInt32LE(16,16);buffer.writeUInt16LE(1,20);buffer.writeUInt16LE(1,22);buffer.writeUInt32LE(rate,24);buffer.writeUInt32LE(rate*2,28);buffer.writeUInt16LE(2,32);buffer.writeUInt16LE(16,34);buffer.write('data',36);buffer.writeUInt32LE(count*2,40);
  for(let i=0;i<count;i++)buffer.writeInt16LE(Math.round(Math.max(-1,Math.min(1,samples[i]/Math.max(max,.001)*peak))*32767),44+i*2);
  fs.writeFileSync(path.join(folder,name+'.wav'),buffer);
}
for(let floor=1;floor<=2;floor++){
  const notes=floor===1?[62,69,65,72,62,67,64,69]:[62,65,69,74,72,69,64,67,62,69,72,77,74,69,65,64];
  write('S_BGM_0'+floor,16,t=>{
    const pad=(Math.sin(tau*hz(38)*t)*.5+Math.sin(tau*hz(45)*t)*.25+Math.sin(tau*hz(53)*t)*.18)*(0.7+0.3*Math.cos(tau*t/8));
    let melody=0;const interval=16/notes.length;
    for(let n=0;n<notes.length;n++)melody+=bell(t-n*interval,hz(notes[n]))*.35;
    const beat=t%(floor===1?2:1);const pulse=Math.sin(tau*(60*beat-5*beat*beat))*Math.exp(-beat*13)*.13;
    // Every voice and pad completes whole cycles; edge fade keeps the loop click-free.
    const edge=Math.min(1,t/.12,(16-t)/.12);
    return (pad*.3+melody+pulse)*edge;
  },.46);
}
