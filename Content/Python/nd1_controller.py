import unreal
from editor_toolset.toolsets.blueprint import BlueprintTools
from nd1_graph import link, value, node, call, clear_graph


def build():
    bp = unreal.load_asset('/Game/BP_DungeonPlayerController')
    variables = BlueprintTools.list_variables(bp)
    if 'CameraYawInverse' not in [str(v) for v in variables]:
        BlueprintTools.add_variable(bp, 'CameraYawInverse', 'bool')
        BlueprintTools.set_variable_instance_editable(bp, 'CameraYawInverse', True)
    BlueprintTools.compile_blueprint(bp)
    graph, editor = clear_graph(bp)
    begin = node(editor, 'イベントを追加|イベントBeginPlay', 0, 0)
    self_node = node(editor, '変数|Getareferencetoself', 0, 180)
    subsystem = node(editor, 'PlayerController|LocalPlayerサブシステム|EnhancedInputLocalPlayerSubsystemを取得', 220, 180)
    context = node(editor, '入力|AddMappingContext', 600, 0)
    link(self_node, 'self', subsystem, 'PlayerController')
    link(subsystem, 'ReturnValue', context, 'self')
    link(begin, 'then', context, 'execute')
    value(context, 'MappingContext', '/Game/IMC_Game.IMC_Game')

    move = node(editor, 'インプット|EnhancedActionEvents|IA_Move', 0, 520)
    pawn = call(editor, '/Script/Engine.Controller.K2_GetPawn', 0, 1040)
    cm = call(editor, '/Script/Engine.GameplayStatics.GetPlayerCameraManager', 0, 1370)
    forward = call(editor, '/Script/Engine.Actor.GetActorForwardVector', 300, 1370)
    flat = call(editor, '/Script/Engine.KismetMathLibrary.Vector_Normal2D', 600, 1370)
    right = call(editor, '/Script/Engine.Actor.GetActorRightVector', 300, 1590)
    xy = call(editor, '/Script/Engine.KismetMathLibrary.BreakVector2D', 300, 760)
    fscale = call(editor, '/Script/Engine.KismetMathLibrary.Multiply_VectorFloat', 900, 1170)
    rscale = call(editor, '/Script/Engine.KismetMathLibrary.Multiply_VectorFloat', 900, 1490)
    combine = call(editor, '/Script/Engine.KismetMathLibrary.Add_VectorVector', 1200, 1170)
    normal = call(editor, '/Script/Engine.KismetMathLibrary.Normal', 1460, 1170)
    movement = call(editor, '/Script/Engine.Pawn.AddMovementInput', 1770, 520)
    value(movement, 'ScaleValue', '1.0')
    link(move, 'Triggered', movement, 'execute')
    link(move, 'ActionValue', xy, 'InVec')
    link(cm, 'ReturnValue', forward, 'self')
    link(cm, 'ReturnValue', right, 'self')
    link(forward, 'ReturnValue', flat, 'A')
    link(flat, 'ReturnValue', fscale, 'A')
    link(xy, 'Y', fscale, 'B')
    link(right, 'ReturnValue', rscale, 'A')
    link(xy, 'X', rscale, 'B')
    link(fscale, 'ReturnValue', combine, 'A')
    link(rscale, 'ReturnValue', combine, 'B')
    link(combine, 'ReturnValue', normal, 'A')
    link(normal, 'ReturnValue', movement, 'WorldDirection')
    link(pawn, 'ReturnValue', movement, 'self')

    camera = node(editor, 'インプット|EnhancedActionEvents|IA_CameraController', 0, 2050)
    multiply = call(editor, '/Script/Engine.KismetMathLibrary.Multiply_DoubleDouble', 400, 2270)
    select = call(editor, '/Script/Engine.KismetMathLibrary.SelectFloat', 760, 2270)
    inverse = editor.add_get_member_variable_node('CameraYawInverse', '')
    inverse.set_node_pos(unreal.IntPoint(400, 2500))
    yaw = call(editor, '/Script/Engine.Pawn.AddControllerYawInput', 1120, 2050)
    camera_pawn = call(editor, '/Script/Engine.Controller.K2_GetPawn', 760, 1930)
    link(camera, 'Triggered', yaw, 'execute')
    link(camera_pawn, 'ReturnValue', yaw, 'self')
    link(camera, 'ActionValue', multiply, 'A')
    value(multiply, 'B', '-1.0')
    link(multiply, 'ReturnValue', select, 'A')
    link(camera, 'ActionValue', select, 'B')
    link(inverse, 'CameraYawInverse', select, 'bPickA')
    link(select, 'ReturnValue', yaw, 'Val')
    editor.add_comment_node('2-1: Register the Enhanced Input mapping context', unreal.Vector2D(-80,-100), unreal.Vector2D(1100,480))
    editor.add_comment_node('2-1: Camera-relative movement on the XY plane; normalize diagonal input', unreal.Vector2D(-80,420), unreal.Vector2D(2200,1400))
    editor.add_comment_node('2-1: Arrow-key camera orbit with optional CameraYawInverse', unreal.Vector2D(-80,1850), unreal.Vector2D(1600,900))
    BlueprintTools.compile_blueprint(bp)
    unreal.EditorAssetLibrary.save_loaded_asset(bp)
    return {'controller': bp.get_path_name(), 'node_count': len(editor.list_all_nodes())}
